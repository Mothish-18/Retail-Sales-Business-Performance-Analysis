-- Retail Sales & Business Performance Analysis
-- Business Analysis Queries

USE retail_sales_db;


-- 1. What is the total revenue, profit and orders?

SELECT
    SUM(Revenue) AS Total_Revenue,
    SUM(Profit) AS Total_Profit,
    COUNT(Order_ID) AS Total_Orders
FROM sales;


-- 2. Which category generates the highest revenue?

SELECT
    Category,
    SUM(Revenue) AS Total_Revenue
FROM sales
GROUP BY Category
ORDER BY Total_Revenue DESC;


-- 3. Which region generates the highest revenue?

SELECT
    Region,
    SUM(Revenue) AS Total_Revenue
FROM sales
GROUP BY Region
ORDER BY Total_Revenue DESC;


-- 4. What are the top 10 best-selling products by revenue?

SELECT
    Product_Name,
    SUM(Revenue) AS Total_Revenue
FROM sales
GROUP BY Product_Name
ORDER BY Total_Revenue DESC
LIMIT 10;


-- 5. What are the top 10 most profitable products?

SELECT
    Product_Name,
    SUM(Profit) AS Total_Profit
FROM sales
GROUP BY Product_Name
ORDER BY Total_Profit DESC
LIMIT 10;


-- 6. Which customers generate the highest revenue?

SELECT
    Customer_ID,
    SUM(Revenue) AS Total_Revenue
FROM sales
GROUP BY Customer_ID
ORDER BY Total_Revenue DESC
LIMIT 10;


-- 7. What is the monthly revenue trend?

SELECT
    YEAR(Order_Date) AS Sales_Year,
    MONTH(Order_Date) AS Sales_Month,
    SUM(Revenue) AS Monthly_Revenue
FROM sales
GROUP BY
    YEAR(Order_Date),
    MONTH(Order_Date)
ORDER BY
    Sales_Year,
    Sales_Month;


-- 8. What is the total quantity sold by category?

SELECT
    Category,
    SUM(Quantity) AS Total_Quantity
FROM sales
GROUP BY Category
ORDER BY Total_Quantity DESC;


-- 9. What is the profit generated by each region?

SELECT
    Region,
    SUM(Profit) AS Total_Profit
FROM sales
GROUP BY Region
ORDER BY Total_Profit DESC;


-- 10. What is the overall profit margin?

SELECT
    SUM(Profit) / SUM(Revenue) * 100 AS Profit_Margin_Percentage
FROM sales;
